/**
 * 轻量文案层（⑨ i18n）。
 *
 * 为什么不引入 next-intl / react-i18next：
 * 1. 全站文案是硬编码中文，一次性抽干净要动几百处，且会与「采集源名/剧名」这类
 *    本来就不能翻译的内容混在一起；
 * 2. 这个站是单人部署的自用镜像，真正的诉求是「让不懂中文的人也能用」，
 *    而不是做多语种产品 —— 抽导航、页脚、设置、播放器工具按钮这些「框架文案」就够；
 * 3. 引入框架还要改路由结构（app/[locale]/），代价远大于收益。
 *
 * 因此做法是：字典 + tr(lang, key) 纯函数，调用方自己从 store 取 lang。
 * 没收录的 key 直接返回 key 本身（不静默成空串），漏翻一眼就能看出来。
 */

