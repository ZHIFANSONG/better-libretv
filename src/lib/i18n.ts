const DICTS: Record<AppLanguage, Dict> = { zh: ZH, en: EN };

/**
 * 翻译函数签名。纯函数（拿不到 hook）需要文案时由组件把 `useT()` 的结果传进来，
 * 与 lib/playback-stats.ts 的 StatsTranslator、lib/quality-menu.ts 的 QualityMenuTranslator 同范式。
 */
export type Translator = (key: string, vars?: Record<string, string | number>) => string;

/**
 * 取文案。vars 用 `{name}` 占位符替换。
 * 未收录的 key 原样返回 —— 宁可界面上出现一个 `nav.xxx`，也不要静默变成空白按钮。
 */
export function tr(lang: AppLanguage, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? ZH;
  // 英文缺词时回落中文，而不是掉回 key：宁可中文也不给用户看占位符
  const text = dict[key] ?? ZH[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_m, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`
  );
}

/**
 * 列表分隔符：中文顿号、英文逗号加空格。
 * 源名列表（"360资源、暴风资源"）不能硬编码顿号，英文界面里那会读成连字。
 */
export function listSep(lang: AppLanguage): string {
  return lang === 'zh' ? '、' : ', ';
}

/** 已收录的 key（测试与漏翻检查用） */
export function dictKeys(lang: AppLanguage): string[] {
  return Object.keys(DICTS[lang] ?? {});
}
